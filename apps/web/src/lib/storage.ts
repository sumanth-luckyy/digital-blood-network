// In-memory fallback for SSR/testing environments where localStorage is not defined
const memoryStore: Record<string, string> = {};

function getStored<T>(key: string, fallback: T): T {
  try {
    if (typeof localStorage !== 'undefined') {
      const val = localStorage.getItem(`bloodlink_${key}`);
      return val ? JSON.parse(val) : fallback;
    }
    const memVal = memoryStore[`bloodlink_${key}`];
    return memVal ? JSON.parse(memVal) : fallback;
  } catch {
    return fallback;
  }
}

function setStored<T>(key: string, value: T): void {
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(`bloodlink_${key}`, JSON.stringify(value));
    } else {
      memoryStore[`bloodlink_${key}`] = JSON.stringify(value);
    }
  } catch (err) {
    console.error('Storage write error', err);
  }
}

